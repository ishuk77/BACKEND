ALTER TABLE groups ADD COLUMN IF NOT EXISTS cycle_closed_by_member_id BIGINT;
ALTER TABLE members ADD COLUMN IF NOT EXISTS sponsor_account_id BIGINT;
ALTER TABLE group_invitations ADD COLUMN IF NOT EXISTS sponsor_account_id BIGINT;

