-- PostgreSQL schema for AVEC Microcredit. Applied automatically when DATABASE_URL is set.
-- IDs remain importable from SQLite; use the data migration script before serving production traffic.

CREATE TABLE IF NOT EXISTS groups (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            country TEXT,
            province TEXT,
            city TEXT,
            currency TEXT,
            phone TEXT,
            wallet REAL DEFAULT 0,
            blocked SMALLINT DEFAULT 0,
            cycle_length INTEGER DEFAULT 6,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        );

CREATE TABLE IF NOT EXISTS members (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id BIGINT,
            member_id TEXT UNIQUE,
            prenom TEXT,
            name TEXT NOT NULL,
            phone TEXT,
            id_number TEXT,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            pin TEXT,
            parrain TEXT,
            role TEXT,
            role_origin TEXT NOT NULL DEFAULT 'member',
            password TEXT,
            wallet REAL DEFAULT 0,
            contribution REAL DEFAULT 0,
            cycle_contribution REAL DEFAULT 0,
            credit REAL DEFAULT 0,
            interest REAL DEFAULT 0,
            repayment REAL DEFAULT 0,
            withdrawals_date TEXT,
            withdrawals_count INTEGER DEFAULT 0,
            refresh_token TEXT,
            credit_request TEXT,
            availability TEXT NOT NULL DEFAULT 'offline',
            profile_photo_filename TEXT,
            FOREIGN KEY (group_id) REFERENCES groups (id) DEFERRABLE INITIALLY IMMEDIATE
        );

CREATE TABLE IF NOT EXISTS history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id BIGINT NOT NULL,
            member_id BIGINT NOT NULL,
            action TEXT NOT NULL,
            date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (group_id) REFERENCES groups (id) DEFERRABLE INITIALLY IMMEDIATE,
            FOREIGN KEY (member_id) REFERENCES members (id) DEFERRABLE INITIALLY IMMEDIATE
        );

CREATE TABLE IF NOT EXISTS chat_messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id BIGINT NOT NULL,
            sender TEXT NOT NULL,
            sender_member_id BIGINT,
            message TEXT NOT NULL,
            recipient TEXT,
            conversation_type TEXT NOT NULL DEFAULT 'group',
            date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (group_id) REFERENCES groups (id) DEFERRABLE INITIALLY IMMEDIATE
        );

CREATE TABLE IF NOT EXISTS message_reactions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            message_id BIGINT NOT NULL,
            member_id BIGINT NOT NULL,
            emoji TEXT NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(message_id, member_id, emoji),
            FOREIGN KEY (message_id) REFERENCES chat_messages (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
            FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE
        );

CREATE TABLE IF NOT EXISTS chat_attachments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id BIGINT NOT NULL,
            uploader_member_id BIGINT NOT NULL,
            message_id BIGINT,
            original_name TEXT NOT NULL,
            stored_name TEXT NOT NULL UNIQUE,
            mime_type TEXT NOT NULL,
            size_bytes INTEGER NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (group_id) REFERENCES groups (id) DEFERRABLE INITIALLY IMMEDIATE,
            FOREIGN KEY (uploader_member_id) REFERENCES members (id) DEFERRABLE INITIALLY IMMEDIATE,
            FOREIGN KEY (message_id) REFERENCES chat_messages (id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE
