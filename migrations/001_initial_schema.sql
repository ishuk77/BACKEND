            confirmed_at TIMESTAMPTZ,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (account_id) REFERENCES platform_accounts(id) DEFERRABLE INITIALLY IMMEDIATE
        );

CREATE TABLE IF NOT EXISTS platform_account_memberships (
